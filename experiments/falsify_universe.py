"""P2: was the BTC result trend following, or hindsight?

P1 found that the 2026 portfolio's only timing edge was on BTC, an asset
picked in 2026 as a past winner. This runs the same rules on a universe
fixed in advance (Quantlab_Research_Plan.md, 2026-11-16), before any result
was seen, with each asset's full history:

  SPY QQQ IWM EFA EEM TLT IEF LQD GLD DBC VNQ BTC-USD ETH-USD

For each asset: walk-forward VolMomentum, out of sample, against a static
holding of the strategy's own average exposure (as in P1). Then an
equal-risk combination of all strategies against the same combination of
the static holdings.

Pass (fixed in the plan before the run): more than half the assets beat
their static benchmark, AND the equal-risk combination beats the static one
with paired block-bootstrap p < 0.10.

Run:  venv\\Scripts\\python.exe experiments\\falsify_universe.py --end 2026-09-30
Writes reports/falsify_p2.md.
"""
import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from falsify_portfolio import leg_study  # same reconstruction as P1
from quantlab.data import fetch
from quantlab.engine import Backtester, compute_metrics
from quantlab.research import paired_block_bootstrap_sharpe_diff, shift_control
from quantlab.research.controls import FixedPositions

UNIVERSE = ["SPY", "QQQ", "IWM", "EFA", "EEM", "TLT", "IEF", "LQD", "GLD", "DBC", "VNQ",
            "BTC-USD", "ETH-USD"]
CRYPTO = {"BTC-USD", "ETH-USD"}
PASS_P = 0.10
RISK_WINDOW = 60   # days of trailing vol for the equal-risk weights
CONTROL_N = 200    # informational here; the pass rule does not use it


def load(symbol: str, end: str) -> pd.DataFrame:
    if symbol in CRYPTO:
        prices = fetch("crypto", symbol, days=6000, source="yahoo")
    else:
        prices = fetch("stock", symbol, period="max")
    return prices.loc[:end]


def on_calendar(equity: pd.Series, calendar: pd.DatetimeIndex) -> pd.Series:
    """Daily returns on the stock calendar; a 24/7 asset's weekend lands on Monday."""
    levels = equity.reindex(calendar.union(equity.index)).ffill().reindex(calendar)
    return levels.pct_change(fill_method=None)


def equal_risk(rets: pd.DataFrame) -> pd.Series:
    """Inverse trailing-vol weights over the legs live that day, known a day ahead."""
    inv = 1 / rets.rolling(RISK_WINDOW, min_periods=RISK_WINDOW).std().shift(1)
    weights = inv.div(inv.sum(axis=1), axis=0)
    return (weights * rets).sum(axis=1, min_count=1).dropna()


def asset_row(symbol: str, leg: dict, prices: pd.DataFrame, bt: Backtester) -> dict:
    strat, static = leg["eq"]["both"], leg["eq"]["static"]
    paired = paired_block_bootstrap_sharpe_diff(strat.pct_change(), static.pct_change(),
                                                365 if symbol in CRYPTO else 252)
    control = shift_control(prices.loc[leg["pos"]["both"].index],
                            FixedPositions(leg["pos"]["both"]), bt, n=CONTROL_N)
    return {"symbol": symbol, "start": strat.index[0].date(),
            "years": (strat.index[-1] - strat.index[0]).days / 365.25,
            "strategy": compute_metrics(strat)["sharpe"], "static": compute_metrics(static)["sharpe"],
            "diff_p": paired["p_value"], "exposure": leg["pos"]["both"].mean(),
            "control_p": control["p_value"]}


def report(rows: list, combo: dict, combo_sharpes: dict, beat: int, passed: bool) -> str:
    lines = ["# P2 falsification: the same rules on a universe fixed in advance", "",
             "Generated by `experiments/falsify_universe.py --end 2026-09-30`. Universe and "
             "thresholds fixed in `Quantlab_Research_Plan.md` before the run.", "",
             "| Asset | OOS from | Years | Strategy | Static (same avg exposure) | Beats static | "
             "Paired p | Avg exposure | Control p |", "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['symbol']} | {r['start']} | {r['years']:.1f} | {r['strategy']:.2f} | "
                     f"{r['static']:.2f} | {'yes' if r['strategy'] > r['static'] else 'no'} | "
                     f"{r['diff_p']:.2f} | {r['exposure']:.2f} | {r['control_p']:.2f} |")
    lines += ["", f"Assets beating their static benchmark: **{beat} of {len(rows)}** "
              f"(needs more than {len(rows) / 2:.1f}).", "",
              "## Equal-risk combination (inverse 60-day vol, stock calendar)", "",
              "| | Sharpe |", "|---|---|",
              f"| strategies | {combo_sharpes['strategy']:.2f} |",
              f"| static holdings | {combo_sharpes['static']:.2f} |", "",
              f"Strategy minus static: {combo['diff']:+.2f} "
              f"(95% interval {combo['ci_low']:+.2f} to {combo['ci_high']:+.2f}, "
              f"one-sided p = {combo['p_value']:.3f}).", "",
              f"## Verdict: {'PASS' if passed else 'FAIL'}", "",
              f"- more than half the assets beat static: {'yes' if beat > len(rows) / 2 else 'NO'}",
              f"- combination beats static with p < {PASS_P}: "
              f"{'yes' if combo['diff'] > 0 and combo['p_value'] < PASS_P else 'NO'}", "",
              "Paired p and control p per asset are informational; the rule uses only the "
              "count and the combination."]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--end", default="2026-09-30")
    args = ap.parse_args()

    bt = Backtester(fee=0.001, slippage=0.0005)
    prices = {s: load(s, args.end) for s in UNIVERSE}
    legs = {s: leg_study(p, bt) for s, p in prices.items()}
    rows = [asset_row(s, legs[s], prices[s], bt) for s in UNIVERSE]

    calendar = prices["SPY"].index
    combo_rets = {v: equal_risk(pd.DataFrame({s: on_calendar(legs[s]["eq"][v], calendar)
                                              for s in UNIVERSE})) for v in ("both", "static")}
    combo = paired_block_bootstrap_sharpe_diff(combo_rets["both"], combo_rets["static"], 252)
    combo_sharpes = {"strategy": compute_metrics((1 + combo_rets["both"]).cumprod(), periods_per_year=252)["sharpe"],
                     "static": compute_metrics((1 + combo_rets["static"]).cumprod(), periods_per_year=252)["sharpe"]}
    beat = sum(r["strategy"] > r["static"] for r in rows)
    passed = beat > len(rows) / 2 and combo["diff"] > 0 and combo["p_value"] < PASS_P

    text = report(rows, combo, combo_sharpes, beat, passed)
    (Path(__file__).resolve().parents[1] / "reports" / "falsify_p2.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
