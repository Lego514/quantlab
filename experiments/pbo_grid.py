"""P3: how likely is it that picking the best vol_momentum parameters overfits?

For each P2 asset, the full-history daily returns of a parameter grid
(lookback 30-250 x target vol 15/25/40%), then CSCV with 16 blocks
(12,870 splits). The case study picks its parameters this way, fold by fold.

Run:  venv\\Scripts\\python.exe experiments\\pbo_grid.py --end 2026-09-30
Writes reports/pbo_p3.md.
"""
import argparse
import sys
from itertools import product
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from falsify_universe import UNIVERSE, load
from quantlab.engine import Backtester
from quantlab.research.pbo import pbo
from quantlab.strategies import VolMomentum

LOOKBACKS = [30, 60, 90, 120, 150, 200, 250]
TARGET_VOLS = [0.15, 0.25, 0.40]
N_BLOCKS = 16
WARMUP = 300  # bars before every config has a position history


def grid_returns(prices: pd.DataFrame, bt: Backtester) -> pd.DataFrame:
    cols = {}
    for lb, tv in product(LOOKBACKS, TARGET_VOLS):
        eq = bt.run(prices, VolMomentum(lookback=lb, target_vol=tv)).equity
        cols[f"{lb}/{tv:.2f}"] = eq.pct_change()
    return pd.DataFrame(cols).iloc[WARMUP:].dropna()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--end", default="2026-09-30")
    args = ap.parse_args()
    bt = Backtester(fee=0.001, slippage=0.0005)
    rows = []
    for s in UNIVERSE:
        out = pbo(grid_returns(load(s, args.end), bt), N_BLOCKS)
        rows.append((s, out))
        print(s, out, flush=True)
    lines = ["# P3: probability of backtest overfitting, vol_momentum grid", "",
             f"Generated by `experiments/pbo_grid.py --end 2026-09-30`. "
             f"{len(LOOKBACKS) * len(TARGET_VOLS)} configurations (lookback "
             f"{LOOKBACKS[0]}-{LOOKBACKS[-1]} x target vol {', '.join(f'{t:.0%}' for t in TARGET_VOLS)}), "
             f"full history per asset, CSCV with {N_BLOCKS} blocks.", "",
             "PBO is the share of splits where the best in-sample configuration ranks in the "
             "bottom half out of sample. Near 0: choosing the best works. Near 0.5 or above: "
             "the choice is noise.", "",
             "| Asset | PBO | Median logit |", "|---|---|---|"]
    lines += [f"| {s} | {o['pbo']:.2f} | {o['median_logit']:+.2f} |" for s, o in rows]
    avg = sum(o["pbo"] for _, o in rows) / len(rows)
    lines += ["", f"Average PBO across the {len(rows)} assets: **{avg:.2f}**.", "",
              "Target vol barely changes Sharpe while positions stay under the 1.0 cap, so "
              "configurations sharing a lookback are near-duplicates; that pulls PBO toward "
              "the lookback choice alone."]
    text = "\n".join(lines) + "\n"
    (Path(__file__).resolve().parents[1] / "reports" / "pbo_p3.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
